export const initialAnimation = () => ({mode:0,step:0});
export function changeAnimation(id,state,event) {
  const config=animations[id];
  if (event.type==='mode' && config.modes[event.mode] && event.mode!==state.mode) return {mode:event.mode,step:0};
  if (event.type==='act' && state.step<config.modes[state.mode].frames.length) return {...state,step:state.step+1};
  return state;
}
