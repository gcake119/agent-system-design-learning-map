export function buildCurriculum(bank) {
  const byId = Object.fromEntries(bank.map(c => [c.id,c]));
  const evidence = [byId.evaluation.pages[0], ...byId.observability.pages, ...byId.evaluation.pages.slice(1)];
  return definitions.map(([id,title,conclusion,objectives],index) => {
    const source = id === 'overview' ? overview : id === 'evidence' ? evidence : byId[id].pages;
    const pages = source.map((p,i) => ({ ...p, objective: p.objective || concepts[id][i] }));
    if (id === 'reliability') {
      pages.push(reveal('工具輸入與輸出都需要檢查', '工具要求案件編號，但助手傳入空值；另一回合雖收到 HTTP 200，內容卻少了附件清單。', ['輸入檢查', '輸出檢查', '後續行動'], ['案件編號為空', '回應缺少 attachments', '準備產生答案'], '驗證工具資料', ['呼叫前攔截，要求補齊案件編號', '標記格式不符，不能當作空清單', '修正資料或交接，不產生缺件結論'], '傳輸成功與業務資料有效是不同條件。輸入與輸出都須驗證格式、必要欄位及適用規則。', '能辨認工具資料不合規，避免將無效輸出當作成功結果。'));
      pages.push(reveal('替代方案必須說明限制', '主要案件查詢服務持續失敗，只有昨天保存的清單可用。', ['主要服務', '替代資料', '對外回覆'], ['重試已達上限', '昨天的附件清單', '今天的狀態未知'], '使用有標示的替代資訊', ['停止呼叫並記錄故障', '標明來源與昨天的時間', '提供歷史資訊，今天是否齊件仍待確認'], 'Fallback 讓工作保留部分價值，但不能把舊資料包裝成最新結果。任務要求最新狀態時，仍需等待恢復或人工確認。', '能選擇替代處理並清楚說明資料時效與未完成部分。'));
    }
    const [intro,a,ac,b,bc,objective,explanation] = reviews[id];
    pages.push({ title: '試著說明：把觀念用在新情境', intro, labels: ['採用的依據', '執行過程', '結果判斷'], before: ['先想想你會怎麼做', '說出你的理由', '再比較兩種結果'], action: '選擇處理方式', objective, review: true, choices: [
      { label:a, cards:ac, feedback:explanation+' 這個做法遺漏了需要檢查的條件。' },
      { label:b, cards:bc, feedback:explanation },
    ] });
    return extendChapter({ id, title, conclusion, objectives, number:index, group:tracks.find(t=>t.ids.includes(id)).name, question:title, description:conclusion, pages });
  });
}
